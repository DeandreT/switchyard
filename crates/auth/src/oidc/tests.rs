#[tokio::test]
async fn refresh_deadline_admission_and_cancellation_close_original_connections() {
    let fixture = Fixture::new().await;
    let verifier = fixture.verifier();
    fixture.replies.lock().unwrap().discovery = Reply::Stall;
    let worker = tokio::spawn({
        let verifier = verifier.clone();
        async move { verifier.refresh().await }
    });
    fixture.entered.notified().await;
    for _ in 0..100 {
        assert_eq!(verifier.refresh().await, Err(OidcError::Busy));
    }
    assert_eq!(fixture.requests.load(Ordering::SeqCst), 1);
    tokio::time::pause();
    tokio::time::advance(Duration::from_secs(2)).await;
    tokio::time::resume();
    assert_eq!(worker.await.unwrap(), Err(OidcError::Timeout));
    assert_eq!(verifier.refresh().await, Err(OidcError::Backoff));
    tokio::time::pause();
    tokio::time::advance(Duration::from_secs(1)).await;
    tokio::time::resume();
    let worker = tokio::spawn({
        let verifier = verifier.clone();
        async move { verifier.refresh().await }
    });
    fixture.entered.notified().await;
    worker.abort();
    assert!(worker.await.unwrap_err().is_cancelled());
    assert_eq!(verifier.refresh().await, Err(OidcError::Backoff));
    // Wait on the original fixture owners' actual socket-close observations,
    // not a sleep or a timeout claimed as graceful drain.
    // Refresh a third time to prove cancellation released admission.
    tokio::time::pause();
    tokio::time::advance(Duration::from_secs(3)).await;
    tokio::time::resume();
    fixture.replies.lock().unwrap().discovery = Reply::Json(
        json!({"issuer": fixture.issuer, "jwks_uri": format!("{}/keys", fixture.issuer)})
            .to_string(),
    );
    verifier.refresh().await.unwrap();
    while fixture.closed.load(Ordering::SeqCst) < 2 {
        fixture.close_observed.notified().await;
    }
    assert_eq!(fixture.closed.load(Ordering::SeqCst), 2);
    fixture.finish().await;
}

