fn rotated_token(issuer: &str, kid: &str) -> String {
    let mut h = header();
    h["kid"] = json!(kid);
    let mut c = claims();
    c["iss"] = json!(issuer);
    let input = format!(
        "{}.{}",
        URL_SAFE_NO_PAD.encode(h.to_string()),
        URL_SAFE_NO_PAD.encode(c.to_string())
    );
    let key = RsaKeyPair::from_pkcs8(
        &STANDARD
            .decode(include_str!("test-key.b64").trim())
            .unwrap(),
    )
    .unwrap();
    let mut signature = vec![0; key.public().modulus_len()];
    key.sign(
        &RSA_PKCS1_SHA256,
        &SystemRandom::new(),
        input.as_bytes(),
        &mut signature,
    )
    .unwrap();
    format!("{input}.{}", URL_SAFE_NO_PAD.encode(signature))
}

#[derive(Clone)]
enum Reply {
    Json(String),
    GatedJson(String, Arc<Notify>),
    Wire(Vec<u8>),
    Stall,
}

struct Replies {
    discovery: Reply,
    jwks: Reply,
}

struct Fixture {
    issuer: String,
    root: rustls::pki_types::CertificateDer<'static>,
    replies: Arc<Mutex<Replies>>,
    requests: Arc<AtomicUsize>,
    connections: Arc<AtomicUsize>,
    closed: Arc<AtomicUsize>,
    close_observed: Arc<Notify>,
    entered: Arc<Notify>,
    stop: watch::Sender<bool>,
    owner: JoinHandle<usize>,
}

impl Fixture {
    async fn new() -> Self {
        let mut ca_params = CertificateParams::new(vec![]).unwrap();
        ca_params.is_ca = IsCa::Ca(BasicConstraints::Unconstrained);
        let ca_key = KeyPair::generate().unwrap();
        let ca = ca_params.self_signed(&ca_key).unwrap();
        let key = KeyPair::generate().unwrap();
        let cert = CertificateParams::new(vec!["issuer.invalid".into()])
            .unwrap()
            .signed_by(&key, &ca, &ca_key)
            .unwrap();
        let config =
            ServerConfig::builder_with_provider(Arc::new(rustls::crypto::ring::default_provider()))
                .with_safe_default_protocol_versions()
                .unwrap()
                .with_no_client_auth()
                .with_single_cert(
                    vec![cert.der().clone()],
                    PrivatePkcs8KeyDer::from(key.serialize_der()).into(),
                )
                .unwrap();
        let acceptor = TlsAcceptor::from(Arc::new(config));
        let listener = TcpListener::bind((Ipv4Addr::LOCALHOST, 0)).await.unwrap();
        let issuer = format!(
            "https://issuer.invalid:{}/tenant",
            listener.local_addr().unwrap().port()
        );
        let replies = Arc::new(Mutex::new(Replies {
            discovery: Reply::Json(
                json!({"issuer": issuer, "jwks_uri": format!("{issuer}/keys")}).to_string(),
            ),
            jwks: Reply::Json(json!({"keys": configuration()["keys"]}).to_string()),
        }));
        let requests = Arc::new(AtomicUsize::new(0));
        let connections = Arc::new(AtomicUsize::new(0));
        let closed = Arc::new(AtomicUsize::new(0));
        let close_observed = Arc::new(Notify::new());
        let entered = Arc::new(Notify::new());
        let (stop, mut stopped) = watch::channel(false);
        let owner = {
            let replies = replies.clone();
            let requests = requests.clone();
            let connections = connections.clone();
            let closed = closed.clone();
            let close_observed = close_observed.clone();
            let entered = entered.clone();
            tokio::spawn(async move {
                let mut workers = JoinSet::new();
                let mut joined = 0;
                loop {
                    tokio::select! {
                        biased;
                        _ = stopped.changed() => break,
                        Some(result) = workers.join_next(), if !workers.is_empty() => {
                            result.unwrap(); joined += 1;
                        },
                        result = listener.accept() => {
                            let (socket, _) = result.unwrap();
                            connections.fetch_add(1, Ordering::SeqCst);
                            let acceptor = acceptor.clone();
                            let replies = replies.clone();
                            let requests = requests.clone();
                            let closed = closed.clone();
                            let close_observed = close_observed.clone();
                            let entered = entered.clone();
                            let mut stopped = stopped.clone();
                            // The fixture itself also bounds live connection owners.
                            assert!(workers.len() < 4);
                            workers.spawn(async move {
                                tokio::select! {
                                    biased;
                                    _ = stopped.changed() => {},
                                    _ = async {
                                        let Ok(mut stream) = acceptor.accept(socket).await else { return; };
                                        let mut request = Vec::new();
                                        loop {
                                            let mut byte = [0];
                                            if stream.read_exact(&mut byte).await.is_err() { return; }
                                            request.push(byte[0]);
                                            assert!(request.len() <= 4096);
                                            if request.ends_with(b"\r\n\r\n") { break; }
                                        }
                                        // Test-only scripted peer, not a production HTTP parser.
                                        let request_text = String::from_utf8(request.clone()).unwrap().to_ascii_lowercase();
                                        assert!(!request_text.contains("authorization:"));
                                        assert!(!request_text.contains("cookie:"));
                                        assert!(!request_text.contains("proxy-"));
                                        let discovery = request.starts_with(b"GET /tenant/.well-known/");
                                        let reply = {
                                            let state = replies.lock().unwrap();
                                            if discovery { state.discovery.clone() } else { state.jwks.clone() }
                                        };
                                        requests.fetch_add(1, Ordering::SeqCst);
                                        entered.notify_one();
                                        match reply {
                                            Reply::Json(body) => {
                                                let wire = format!("HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{body}", body.len());
                                                let _ = stream.write_all(wire.as_bytes()).await;
                                            },
                                            Reply::GatedJson(body, gate) => {
                                                gate.notified().await;
                                                let wire = format!("HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{body}", body.len());
                                                let _ = stream.write_all(wire.as_bytes()).await;
                                            },
                                            Reply::Wire(wire) => { let _ = stream.write_all(&wire).await; },
                                            Reply::Stall => {
                                                // An actual client close, not elapsed time, proves
                                                // that cancellation dropped the active socket.
                                                let mut byte = [0];
                                                match stream.read(&mut byte).await {
                                                    Ok(0) | Err(_) => { closed.fetch_add(1, Ordering::SeqCst); close_observed.notify_one(); },
                                                    _ => panic!("unexpected client data"),
                                                }
                                            },
                                        }
                                        let _ = stream.shutdown().await;
                                    } => {},
                                }
                            });
                        },
                    }
                }
                drop(listener);
                while let Some(result) = workers.join_next().await {
                    result.unwrap();
                    joined += 1;
                }
                joined
            })
        };
        Self {
            issuer,
            root: ca.der().clone(),
            replies,
            requests,
            connections,
            closed,
            close_observed,
            entered,
            stop,
            owner,
        }
    }

    fn local(&self) -> JwtPolicy {
        let mut config = configuration();
        config["issuer"] = json!(self.issuer);
        config["bindings"].as_array_mut().unwrap().push(json!({
            "subject": "consumer", "scope": "amqps://tenant.example/other", "permissions": ["listen"]
        }));
        JwtPolicy::from_json(&config.to_string()).unwrap()
    }

    fn transport(&self) -> HttpsTransport {
        HttpsTransport::new(
            PinnedEndpoint::loopback_fixture(&format!(
                "{}/.well-known/openid-configuration",
                self.issuer
            ))
            .unwrap(),
            PinnedEndpoint::loopback_fixture(&format!("{}/keys", self.issuer)).unwrap(),
            vec![self.root.clone()],
        )
        .unwrap()
    }

    fn verifier(&self) -> OidcVerifier {
        OidcVerifier::new(
            self.local(),
            self.transport(),
            CachePolicy {
                maximum_freshness: Duration::from_secs(10),
                refresh_interval: Duration::from_secs(1),
                failure_backoff: Duration::from_secs(1),
                refresh_timeout: Duration::from_secs(2),
            },
        )
        .unwrap()
    }

    fn token(&self, kid: &str, sub: &str) -> String {
        let mut header = header();
        header["kid"] = json!(kid);
        let mut claims = claims();
        claims["iss"] = json!(self.issuer);
        claims["sub"] = json!(sub);
        claims["roles"] = json!(["manage", "admin"]);
        signed(&header, &claims)
    }

    fn keys(&self, kids: &[&str]) {
        let keys: Vec<_> = kids
            .iter()
            .map(|kid| {
                let mut key = configuration()["keys"][0].clone();
                key["kid"] = json!(kid);
                key
            })
            .collect();
        self.replies.lock().unwrap().jwks = Reply::Json(json!({"keys": keys}).to_string());
    }

    async fn finish(self) {
        let accepted = self.connections.load(Ordering::SeqCst);
        self.stop.send(true).unwrap();
        // No timeout-as-drain: the original owner joins every accepted worker.
        assert_eq!(self.owner.await.unwrap(), accepted);
    }
}

#[tokio::test]
async fn tls_rotation_key_removal_shared_freshness_and_local_rights() {
    let fixture = Fixture::new().await;
    let verifier = fixture.verifier();
    let retained = verifier.clone();
    let legacy = fixture.local();
    let old = fixture.token("key-1", "producer");
    assert_eq!(
        verifier.validate(&old, &requested(), 100),
        Err(OidcError::Unavailable)
    );
    verifier.refresh().await.unwrap();
    let issued = verifier.validate(&old, &requested(), 100).unwrap();
    assert_eq!(issued.permissions(), PermissionSet::SEND);
    assert_eq!(
        verifier.validate(&fixture.token("missing", "producer"), &requested(), 100),
        Err(OidcError::Jwt(JwtError::UnknownKey))
    );
    let requests = fixture.requests.load(Ordering::SeqCst);
    for _ in 0..100 {
        assert!(
            verifier
                .validate(&fixture.token("missing", "producer"), &requested(), 100)
                .is_err()
        );
    }
    assert_eq!(fixture.requests.load(Ordering::SeqCst), requests);
    assert_eq!(
        verifier.validate(&fixture.token("key-1", "unknown"), &requested(), 100),
        Err(OidcError::Jwt(JwtError::UnknownSubject))
    );
    assert_eq!(
        verifier.validate(&fixture.token("key-1", "consumer"), &requested(), 100),
        Err(OidcError::Jwt(JwtError::ScopeMismatch))
    );
    let consumer = verifier
        .validate(
            &fixture.token("key-1", "consumer"),
            &ResourceScope::entity("tenant.example", "other").unwrap(),
            100,
        )
        .unwrap();
    assert!(!consumer.same_principal(&issued));
    assert_eq!(consumer.permissions(), PermissionSet::LISTEN);
    assert!(!issued.allows(&requested(), Permission::Manage, 100));
    assert!(!issued.allows(
        &ResourceScope::entity("unrelated.example", "orders").unwrap(),
        Permission::Send,
        100
    ));

    tokio::time::pause();
    tokio::time::advance(Duration::from_secs(1)).await;
    tokio::time::resume();
    fixture.keys(&["key-1", "key-2"]);
    verifier.refresh().await.unwrap();
    assert!(
        retained
            .validate(&fixture.token("key-2", "producer"), &requested(), 100)
            .is_ok()
    );
    assert!(retained.validate(&old, &requested(), 100).is_ok());
    tokio::time::pause();
    tokio::time::advance(Duration::from_secs(1)).await;
    tokio::time::resume();
    fixture.keys(&["key-2"]);
    verifier.refresh().await.unwrap();
    assert_eq!(
        retained.validate(&old, &requested(), 100),
        Err(OidcError::Jwt(JwtError::UnknownKey))
    );
    // Removal prevents new verification, not persistent revocation of issued grants.
    assert!(issued.allows(&requested(), Permission::Send, 199));
    assert!(!issued.allows(&requested(), Permission::Send, 200));
    assert!(legacy.validate(&old, &requested(), 100).is_ok());
    tokio::time::pause();
    tokio::time::advance(Duration::from_secs(10)).await;
    assert_eq!(
        retained.validate(&fixture.token("key-2", "producer"), &requested(), 100),
        Err(OidcError::Unavailable)
    );
    assert!(legacy.validate(&old, &requested(), 100).is_ok());
    tokio::time::resume();
    fixture.finish().await;
}

#[tokio::test]
async fn malformed_refreshes_are_atomic_and_do_not_extend_freshness() {
    let fixture = Fixture::new().await;
    let verifier = fixture.verifier();
    let old = fixture.token("key-1", "producer");
    verifier.refresh().await.unwrap();
    let good = configuration()["keys"][0].clone();
    let mut new = good.clone();
    new["kid"] = json!("key-2");
    let mut bad = good.clone();
    bad["e"] = json!("Aw");
    for invalid in [
        format!("{{\"keys\":[{new},{bad}]}}"),
        format!("{{\"keys\":[{new}],\"keys\":[]}}"),
        json!({"keys": [good.clone(), good.clone()]}).to_string(),
        json!({"keys": vec![good; 9]}).to_string(),
        "{\"keys\":[],\"metadata\":{\"x\":1,\"\\u0078\":2}}".into(),
        "[[[[[[[[[[]]]]]]]]]]".into(),
        "{ broken".into(),
    ] {
        tokio::time::pause();
        tokio::time::advance(Duration::from_secs(1)).await;
        tokio::time::resume();
        fixture.replies.lock().unwrap().jwks = Reply::Json(invalid);
        assert_eq!(verifier.refresh().await, Err(OidcError::Document));
        assert!(verifier.validate(&old, &requested(), 100).is_ok());
        assert_eq!(
            verifier.validate(&fixture.token("key-2", "producer"), &requested(), 100),
            Err(OidcError::Jwt(JwtError::UnknownKey))
        );
        assert_eq!(verifier.refresh().await, Err(OidcError::Backoff));
    }
    tokio::time::pause();
    tokio::time::advance(Duration::from_secs(3)).await;
    assert_eq!(
        verifier.validate(&old, &requested(), 100),
        Err(OidcError::Unavailable)
    );
    tokio::time::resume();
    fixture.keys(&[]);
    verifier.refresh().await.unwrap();
    assert_eq!(
        verifier.validate(&old, &requested(), 100),
        Err(OidcError::Jwt(JwtError::UnknownKey))
    );
    fixture.finish().await;
}

#[tokio::test]
async fn distinct_rsa_material_rotates_under_new_and_reused_key_ids() {
    let fixture = Fixture::new().await;
    let verifier = fixture.verifier();
    let old = fixture.token("key-1", "producer");
    verifier.refresh().await.unwrap();
    let mut new = configuration()["keys"][0].clone();
    new["n"] = json!(ROTATED_MODULUS);
    new["kid"] = json!("rotated");
    let rotated = rotated_token(&fixture.issuer, "rotated");
    assert_eq!(
        verifier.validate(&rotated, &requested(), 100),
        Err(OidcError::Jwt(JwtError::UnknownKey))
    );
    tokio::time::pause();
    tokio::time::advance(Duration::from_secs(1)).await;
    tokio::time::resume();
    fixture.replies.lock().unwrap().jwks =
        Reply::Json(json!({"keys": [configuration()["keys"][0], new.clone()]}).to_string());
    verifier.refresh().await.unwrap();
    assert!(verifier.validate(&rotated, &requested(), 100).is_ok());
    assert!(verifier.validate(&old, &requested(), 100).is_ok());
    // Reusing a kid still replaces its key atomically, never unions old material.
    new["kid"] = json!("key-1");
    tokio::time::pause();
    tokio::time::advance(Duration::from_secs(1)).await;
    tokio::time::resume();
    fixture.replies.lock().unwrap().jwks = Reply::Json(json!({"keys": [new]}).to_string());
    verifier.refresh().await.unwrap();
    assert!(
        verifier
            .validate(&rotated_token(&fixture.issuer, "key-1"), &requested(), 100)
            .is_ok()
    );
    assert_eq!(
        verifier.validate(&old, &requested(), 100),
        Err(OidcError::Jwt(JwtError::InvalidSignature))
    );
    assert_eq!(
        verifier.validate(&rotated, &requested(), 100),
        Err(OidcError::Jwt(JwtError::UnknownKey))
    );
    fixture.finish().await;
}

